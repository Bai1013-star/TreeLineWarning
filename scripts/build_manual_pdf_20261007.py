def mixed(text,bold=False):
    text=escape(text)
    return re.sub(r'[A-Za-z0-9][A-Za-z0-9 ._/:()<>+=%~-]*',
                  lambda m:f'<font name="{"TimesBoldLocal" if bold else "TimesLocal"}">{m.group()}</font>',text)

def p(text,kind='body'):
    story.append(Paragraph(mixed(text,kind in ('h1','h2')),styles[kind]))

def section(title,paragraphs):
    if story:story.append(PageBreak())
    p(title,'h1')
    for item in paragraphs:
        if isinstance(item,tuple):p(item[1],item[0])
        else:p(item)

def figure(name,caption):
    file=ROOT/'验收20261007补填便携/缺失测量界面测试'/name
