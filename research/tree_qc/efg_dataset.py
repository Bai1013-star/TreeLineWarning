"""Training data source for the Public Pilot.

Model-selection examples are produced by the **frozen** ``GateDDataset`` — the same class,
the same generator, the same sampler, the same provenance authorization and the same
digests the Gate D acceptance was granted against. This module adds exactly two things on
top, and neither can change what an example is:

* **a byte-verified feature cache**, so a restarted run does not spend hours regenerating
  identical tensors (:mod:`efg_cache`). Every cached entry carries the SHA-256 of its own
  feature block; a mismatch is a miss and the example is regenerated by the frozen
  pipeline. The frozen ``DatasetItem`` does not expose the sampler index block, so the
  cache stores features only — those are the entitlement the trainer consumes, and the
  index-level parity of the shared pipeline is proven separately on live data by
  ``efg_heldout.parity_report``.
* **batch preloading**, so per-candidate geometry is read from disk once instead of once
  per (candidate, class, severity) cell.

No held-out partition is reachable from here: :func:`build_model_selection_source` accepts
only ``train`` and ``validation``, which the frozen ``DatasetConfig`` independently
enforces as well.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import efg_cache as cache_module
import gate_d_dataset as dataset_module
import gate_d_diagnostic as diagnostic_module
import gate_d_sampler as sampler_module
import numpy as np
from gate_d_provenance import MODEL_SELECTION_PARTITIONS

SOURCE_VERSION = 'EFG_MODEL_SELECTION_SOURCE_V1'


class SourceError(RuntimeError):
    pass


class NotApplicableExample(Exception):
    """A declared spec whose defect the candidate's real geometry cannot support.

    ``gate_d_generator`` raises ``NotApplicableError`` for these and the frozen
    ``GateDDataset`` propagates it. Over a full partition that is fatal for the run, and
    substituting a different example would be a silently mislabelled example. The EFG
    layer therefore exposes the condition as a typed exclusion, so the trainer can drop the
    example from its batch and the evaluator can remove it from the metric population with
    the reason recorded and counted.
    """

    def __init__(self, key: str, reason: str, detail: dict | None = None):
        super().__init__(f'{key}: {reason}')
        self.key = key
        self.reason = reason
        self.detail = detail or {}


def spec_list_digest(specs) -> str:
    """Ordered digest of the frozen spec list, used as the cache contract component."""
    rows = [spec.as_row() for spec in specs]
    return hashlib.sha256(json.dumps(rows, sort_keys=True,
                                     separators=(',', ':')).encode('utf-8')).hexdigest()


class CachedExampleSource:
    """The frozen ``GateDDataset`` plus a verified cache and batch preloading.

    ``__getitem__`` still calls the frozen dataset on a cache miss. A hit returns stored
    features only after their digest matches the recorded one, together with the frozen
    provenance row (candidate, class, severity and the full sampler diagnostics).
    """

    def __init__(self, dataset, cache: cache_module.FeatureCache | None = None,
                 preload: bool = True):
        self.dataset = dataset
        self.cache = cache
        self.points = int(dataset.config.points)
        self._provenance_cache: dict[int, dict] = {}
        self.exclusions: dict[str, dict] = {}
        self.preloaded_candidates = 0
        if preload:
            self.preload()

    # --- construction -----------------------------------------------------
    @classmethod
    def build(cls, config, provenance, cache_root: Path | str | None = None,
              use_cache: bool = True, preload: bool = True,
              generator_digest: str | None = None) -> CachedExampleSource:
        if config.partition not in MODEL_SELECTION_PARTITIONS:
            raise SourceError(
                f'{config.partition!r} is not a model-selection partition; held-out data '
                'is only reachable through the EFG held-out adapter')
        candidate_ids = list(provenance.candidates(config.partition))
        if config.partition == 'train' and config.max_train_candidates is not None:
            candidate_ids = candidate_ids[:config.max_train_candidates]
        if (config.partition == 'validation'
                and config.max_validation_candidates is not None):
            candidate_ids = candidate_ids[:config.max_validation_candidates]
        dataset = dataset_module.GateDDataset(
            dataset_module.DatasetConfig(
                partition=config.partition, points=config.points,
                repeats=config.repeats, seed_base=config.seed_base),
            provenance, candidate_ids=candidate_ids, cache_root=config.cache_root)
        cache = None
        if use_cache and cache_root is not None:
            key = cache_module.cache_key(
                provenance, config.partition, config.points, config.repeats,
                config.seed_base, spec_list_digest(dataset.specs),
                generator_digest or diagnostic_module.generator_digest(),
                sampler_module.SAMPLER_VERSION)
            cache = cache_module.FeatureCache(cache_root, key)
        return cls(dataset, cache, preload=preload)

    # --- dataset protocol -------------------------------------------------
    def __len__(self) -> int:
        return len(self.dataset)

    def preload(self, candidate_ids=None) -> None:
        self.dataset.preload(candidate_ids)
        self.preloaded_candidates = len({spec.candidate_id for spec in self.dataset.specs})

    def prewarm(self, tracker=None, progress_every: int = 2000) -> dict:
        """Generate and cache every declared example once, up front.

        Doing this before training turns the first epoch from a full regeneration pass into
        a memory-mapped read, and it surfaces the not-applicable specs as a measured count
        instead of a mid-epoch failure. A failure here is fatal and happens before any GPU
        time is spent.
        """
        import time as _time
        started = _time.time()
        generated = 0
        excluded = 0
        for index in range(len(self.dataset)):
            spec = self.dataset.specs[index]
            record = self.exclusion(index, spec.key)
            if record is not None:
                excluded += 1
                if tracker is not None:
                    tracker.record(spec.key, str(record.get('reason', 'not_applicable')))
                continue
            try:
                self[index]
                generated += 1
            except NotApplicableExample as exc:
                excluded += 1
                if tracker is not None:
                    tracker.record(exc.key, exc.reason)
            if progress_every and (index + 1) % progress_every == 0:
                print(f'      prewarm {index + 1}/{len(self.dataset)} '
                      f'({generated} generated, {excluded} not applicable)', flush=True)
        return {'declared': len(self.dataset), 'generated': generated,
                'excluded': excluded, 'seconds': round(_time.time() - started, 3),
                'cache': self.cache_stats()}

    def __getitem__(self, index: int) -> dataset_module.DatasetItem:
        """The frozen item, a cached copy of it, or a typed ``NotApplicableExample``.

        The exclusion is a property of the frozen pipeline, not of this wrapper: it is
        raised by ``gate_d_generator`` and re-raised here after being recorded, so a
        restart does not have to rediscover it.
        """
        spec = self.dataset.specs[index]
        if self.cache is not None:
            exclusion = self.cache.exclusion(index, spec.key)
            if exclusion is not None:
                self.exclusions[spec.key] = exclusion
                raise NotApplicableExample(spec.key, exclusion.get('reason', 'unknown'),
                                           exclusion.get('detail'))
            hit = self.cache.get(index, spec.key)
            if hit is not None:
                features, label, provenance = hit
                if provenance is None:
                    provenance = self.dataset[index].provenance
                    self._provenance_cache[index] = provenance
                return dataset_module.DatasetItem(features=features, label=int(label),
                                                  key=spec.key, provenance=provenance)
        try:
            item = self.dataset[index]
        except dataset_module.DatasetError as exc:
            reason, _, detail = str(exc).partition(': ')
            _, _, detail = detail.partition('is not applicable: ')
            reason, _, payload = detail.partition(' ')
            record = {'reason': reason or 'not_applicable', 'detail': payload[:200],
                      'key': spec.key}
            self.exclusions[spec.key] = record
            if self.cache is not None:
                self.cache.record_exclusion(index, spec.key, record['reason'],
                                            {'detail': record['detail']})
            raise NotApplicableExample(spec.key, record['reason'],
                                       {'detail': record['detail']}) from exc
        if self.cache is not None:
            self.cache.put(index, spec.key, item.features, item.label, item.provenance)
            self.cache.regenerated += 1
        return item

    # --- exclusions -------------------------------------------------------
    @property
    def exclusion_summary(self) -> dict:
        by_class: dict[str, int] = {}
        for key in self.exclusions:
            parts = key.split('|')
            example_class = parts[2] if len(parts) > 2 else 'UNKNOWN'
            by_class[example_class] = by_class.get(example_class, 0) + 1
        reasons: dict[str, int] = {}
        for record in self.exclusions.values():
            reason = str(record.get('reason', 'unknown'))
            reasons[reason] = reasons.get(reason, 0) + 1
        return {'declared': len(self.dataset.specs), 'excluded': len(self.exclusions),
                'realised': len(self.dataset.specs) - len(self.exclusions),
                'excluded_fraction': (round(len(self.exclusions)
                                            / max(1, len(self.dataset.specs)), 6)),
                'by_class': dict(sorted(by_class.items())),
                'by_reason': dict(sorted(reasons.items()))}

    # --- reporting --------------------------------------------------------
    def digest(self) -> str:
        return self.dataset.digest()

    def restart_state(self) -> dict:
        state = self.dataset.restart_state()
        state['source_version'] = SOURCE_VERSION
        state['preloaded_candidates'] = self.preloaded_candidates
        state['exclusions'] = self.exclusion_summary
        if self.cache is not None:
            state['cache'] = self.cache.stats()
        return state

    def class_balance(self) -> dict:
        return self.dataset.class_balance()

    def manifest(self) -> list[dict]:
        return self.dataset.manifest()

    def cache_stats(self) -> dict:
        return self.cache.stats() if self.cache is not None else {'enabled': False}

    def exclusion(self, index: int, spec_key: str) -> dict | None:
        """A recorded exclusion, from the live registry or from the persisted cache."""
        record = self.exclusions.get(spec_key)
        if record is not None:
            return record
        if self.cache is not None:
            stored = self.cache.exclusion(index, spec_key)
            if stored is not None:
                return stored
        return None


def build_model_selection_source(config, provenance, cache_root=None, use_cache=True,
                                 preload=True, generator_digest=None):
    return CachedExampleSource.build(config, provenance, cache_root, use_cache,
                                     preload, generator_digest)


def verify_cache(source: CachedExampleSource, indices, label: str = 'cache') -> dict:
    """Prove a sample of cached entries is byte-identical to fresh frozen generation.

    The cache is re-used across restarts, so it is treated as an untrusted store: this
    routine regenerates each requested index through the frozen pipeline and compares the
    feature tensor byte for byte. A mismatch is ``STOP_DATASET_FINGERPRINT_CHANGED`` —
    the cache is never "repaired" silently, because a silently repaired cache is a
    silently mislabelled example.
    """
    indices = list(indices)
    if source.cache is None:
        return {'label': label, 'checked': 0, 'enabled': False, 'verdict': 'NOT_APPLICABLE'}
    mismatches = []
    for index in indices:
        spec = source.dataset.specs[index]
        hit = source.cache.get(index, spec.key)
        if hit is None:
            mismatches.append({'index': index, 'key': spec.key, 'issue': 'cache miss'})
            continue
        cached_features = hit[0]
        fresh = source.dataset[index]
        if not np.array_equal(cached_features, fresh.features):
            mismatches.append({
                'index': index, 'key': spec.key, 'issue': 'feature bytes differ',
                'cached_sha256': cache_module.digest_array(cached_features),
                'fresh_sha256': cache_module.digest_array(fresh.features)})
        elif hit[1] != int(fresh.label):
            mismatches.append({'index': index, 'key': spec.key,
                               'issue': 'label differs', 'cached': hit[1],
                               'fresh': int(fresh.label)})
    result = {'label': label, 'enabled': True, 'checked': len(indices),
              'mismatch_count': len(mismatches), 'mismatches': mismatches[:10],
              'verdict': 'PASS' if not mismatches else 'FAIL'}
    if mismatches:
        raise SourceError(
            f'STOP_DATASET_FINGERPRINT_CHANGED: {len(mismatches)} cached example(s) do '
            f'not match fresh frozen generation; first: {mismatches[0]}')
    return result
