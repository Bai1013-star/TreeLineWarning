  await warning.locator('#integratedWeatherDialog').waitFor({state:'visible'});
  await warning.locator('#integratedTemperature').fill('8');
  await back.click();
  await warning.locator('#integratedWeatherDialog').waitFor({state:'hidden'});
  assert.equal(await warning.locator('#integratedTemperature').inputValue(),'8');
  await warning.locator('#singleMode').click();
  await warning.locator('#generateReport').click();
  await warning.locator('#resultPage').waitFor({state:'visible',timeout:60000});
  const report=await warning.locator('#reportOutput').textContent();
  // Twin stays in a separate frame: return must not reload the prediction document.
  await warning.locator('body').evaluate(node=>node.dataset.navigationMarker='preserved');
