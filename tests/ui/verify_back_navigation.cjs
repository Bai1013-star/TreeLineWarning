  await warning.locator('#runBatchPrediction').waitFor({state:'visible'});
  await page.locator('#ribbonHistory').click();
  await warning.locator('#historyPage').waitFor({state:'visible'});
  await back.click();
  await warning.locator('#batchEntry').waitFor({state:'visible'});
  assert.equal(await warning.locator('#batchPreview tbody tr').count(),1);
  assert.equal(await warning.locator('#batchPaste').inputValue(),'tree_id,height,clearance_distance\n987,12,5');
  await back.click();
  await warning.locator('#singleEntry').waitFor({state:'visible'});
  assert.equal(await warning.locator('#height').inputValue(),'12.34');
