  await page.route('**/api/desktop/workspace',route=>route.fulfill({json:{...fixture,ui_state:preparation,tree_review_ready:false,can_predict:false,capability:{available:true,unit_confirmed:preparation==='TOPOLOGY_READY',coordinate_declaration:{unit_status:'METRE'},details:{format:'LAS'}}}}));
