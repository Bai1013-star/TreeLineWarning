const {chromium}=require(process.env.PLAYWRIGHT_MODULE);
const fs=require('node:fs'),assert=require('node:assert/strict');
(async()=>{
  const urls=JSON.parse(fs.readFileSync(process.env.REAL_SERVERS,'utf8'));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage(),checks=[],errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const context=await(await page.request.get(urls.warning+'integrated/context',{timeout:180000})).json();
  const workspace=await(await page.request.get(urls.processing+'api/desktop/workspace')).json();
  assert.equal(context.trees.length,workspace.batch.final_tree_count);
  assert.ok(context.trees.some(tree=>tree.diameter!=null));
  let requests=0;
  await page.route('**/integrated/context',async route=>{
    requests++;await new Promise(resolve=>setTimeout(resolve,18000));
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(context)});
  });
  await page.goto(urls.warning+'?workspace=data');
  await page.waitForFunction(()=>typeof loadIntegratedMode==='function');
  const pending=page.evaluate(()=>Promise.all([loadIntegratedMode(true),loadIntegratedMode(true)]));
  await page.waitForTimeout(16000);
  assert.ok((await page.locator('#processedDataStatus').innerText()).includes('正在读取'));
  await pending;
  assert.equal(requests,1);
  assert.equal(await page.locator('#processedDataBody tr').count(),context.trees.length);
  checks.push({name:'18秒冷读取超过旧15秒限制仍成功，重复调用合并',requests,rows:context.trees.length});
  await page.unroute('**/integrated/context');
  await page.route('**/integrated/context',route=>route.abort('failed'));
  await page.locator('#refreshProcessedData').click();
  await page.locator('#refreshProcessedData:not([disabled])').waitFor();
  const failed=await page.locator('#processedDataStatus').innerText();
  assert.ok(failed.includes('连接失败'));
  assert.ok(!failed.includes('刷新完成'));
  assert.equal(await page.locator('#applyProcessedData').isDisabled(),true);
  assert.equal(await page.locator('#integratedGenerate').isDisabled(),true);
  await page.unroute('**/integrated/context');
  await page.locator('#refreshProcessedData').click();
  await page.locator('#refreshProcessedData:not([disabled])').waitFor({timeout:180000});
  assert.equal(await page.locator('#processedDataBody tr').count(),context.trees.length);
  assert.equal(await page.locator('#applyProcessedData').isDisabled(),false);
  checks.push({name:'失败提示准确并禁止预测；刷新可恢复',passed:true});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(process.env.REAL_OUTPUT+'/cold_data_checks.json',JSON.stringify(checks,null,2));
  console.log(JSON.stringify(checks));await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
