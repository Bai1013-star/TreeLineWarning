const {chromium}=require(process.env.PLAYWRIGHT_MODULE);
const fs=require('node:fs'),assert=require('node:assert/strict');
(async()=>{
  const urls=JSON.parse(fs.readFileSync(process.env.REAL_SERVERS,'utf8'));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  const note=(name,detail)=>{checks.push({name,detail});console.log(JSON.stringify({name,detail}));};
  await page.goto(urls.processing+'step2');
  await page.waitForFunction(()=>window.TreeLineTreeReviewApp?.state.treeMap.size>0,{},{timeout:90000});
  const original=await page.locator('#treetable tbody tr').count();
  note('真实点云复核加载',{trees:original,status:await page.locator('#viewer-renderer-status').textContent()});
  for(const id of ['btn-view-reset','btn-view-top','btn-view-side'])await page.locator('#'+id).click();
  await page.locator('#toggle-labels').uncheck();await page.locator('#toggle-labels').check();
  await page.locator('#btn-next').click();await page.locator('#btn-prev').click();
  note('视角、编号、上一棵下一棵',await page.locator('#current-tree').textContent());
  await page.locator('#btn-trim-lasso').click();await page.keyboard.press('Escape');
  await page.locator('#btn-trim-component').click();await page.keyboard.press('Escape');
  note('套索和团块工具进入取消','passed; 未提交删除');
  await page.evaluate(()=>window.TreeLineTreeReviewApp.state.selected.clear());
  const rows=page.locator('#treetable tbody tr');await rows.nth(0).click();await rows.nth(1).click({modifiers:['Control']});
  await page.locator('#btn-merge').click();
  await page.waitForFunction(n=>window.TreeLineTreeReviewApp.state.treeMap.size===n,original-1,{timeout:120000});
  await page.waitForFunction(()=>!window.TreeLineTreeReviewApp.state.editingBusy,{},{timeout:120000});
  await page.locator('#btn-undo').click();
  await page.waitForFunction(n=>window.TreeLineTreeReviewApp.state.treeMap.size===n,original,{timeout:120000});
  await page.waitForFunction(()=>!window.TreeLineTreeReviewApp.state.editingBusy,{},{timeout:120000});
  note('合并和撤销','完整点成员恢复');
  await page.locator('#treetable tbody tr').nth(0).click();
  await page.locator('#btn-delete').click();
  await page.waitForFunction(n=>window.TreeLineTreeReviewApp.state.treeMap.size===n,original-1,{timeout:120000});
  await page.waitForFunction(()=>!window.TreeLineTreeReviewApp.state.editingBusy,{},{timeout:120000});
  await page.locator('#btn-undo').click();
  await page.waitForFunction(n=>window.TreeLineTreeReviewApp.state.treeMap.size===n,original,{timeout:120000});
  await page.waitForFunction(()=>!window.TreeLineTreeReviewApp.state.editingBusy,{},{timeout:120000});
  note('删除和撤销','仅验收项目；完整点成员恢复');
  await page.locator('#treetable tbody tr').nth(0).click();await page.locator('#btn-dbh-review').click();
  await page.waitForURL('**/dbh-review');await page.waitForFunction(()=>document.querySelector('#tree-count').textContent!=='读取中',{},{timeout:120000});
  note('胸径复核列表',await page.locator('#tree-list-note').textContent());
  const selectable=page.locator('#tree-list button:not([disabled])');
  if(await selectable.count()){
    await selectable.first().click();await page.locator('#btn-prepare').click();
    await page.waitForFunction(()=>!document.querySelector('#review-status').textContent.includes('正在'),{},{timeout:180000});
    note('原始LAS胸径证据',await page.locator('#review-status').textContent());
  }
  await page.screenshot({path:process.env.REAL_OUTPUT+'/dbh_real.png',fullPage:true});
  note('页面脚本异常',errors);assert.deepEqual(errors,[]);
  fs.writeFileSync(process.env.REAL_OUTPUT+'/review_checks.json',JSON.stringify(checks,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
